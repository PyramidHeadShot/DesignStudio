export default function (pi: ExtensionAPI) {
  // Рендер записи справки в чате (не попадает в контекст LLM)
  pi.registerEntryRenderer("russian-help", (_entry, _context, theme) => {
    return new Text(theme.fg("dim", HELP_LINES.join("\n")));
  });

  // Русскоязычное имя и дубль латиницей — на случай проблем с вводом кириллицы
  const handler = async (_args: string, _ctx: unknown) => {
    pi.appendEntry("russian-help", {});
  };

  pi.registerCommand("помощь", {
    description: "Справка по командам pi на русском",
    handler,
  });
  pi.registerCommand("ru-help", {
    description: "Справка по командам pi на русском (Russian help)",
    handler,
  });
}
